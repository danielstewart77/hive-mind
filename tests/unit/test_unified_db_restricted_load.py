"""A load named for some stores must not reach the stores it was not named for.

Every test here writes its own SQLite stores and its own Postgres schema, so
nothing moves when a row is deleted from the live hive. The schema is an
input; the code under test is the loader.

The case these exist for was found by the spec grill on the cutover story on
2026-11-06 and is the reason it was split: the command that was going to
finish the cutover reads every source, truncates every placed table, and
refills from frozen snapshots — so for the three services already living on
Postgres it rewinds them to the day their file was frozen, and reports a
clean run, because drift compares the snapshot against a file that has not
moved.
"""

from __future__ import annotations

import asyncio
import os
import sqlite3
import subprocess
import uuid
from pathlib import Path

import asyncpg
import pytest

from unified_db import cutover, load_data, preflight, schema_map

CONTAINER = "hive-postgres"
DB_USER = "hive"
HOST_PORT = 5433

#: The scratch schema these tests load into: two sources being switched and
#: one that is already on Postgres and has moved on since its file froze.
DDL = """
CREATE EXTENSION IF NOT EXISTS vector;
CREATE SCHEMA core;
CREATE SCHEMA memory;
CREATE SCHEMA board;
CREATE TABLE core.minds (id text PRIMARY KEY, name text);
CREATE TABLE core.sessions (
    id text PRIMARY KEY,
    mind_id text REFERENCES core.minds(id) ON DELETE RESTRICT);
CREATE TABLE memory.notes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    body text);
CREATE TABLE board.cards (
    id text PRIMARY KEY,
    mind_id text,
    CONSTRAINT cards_mind_id_fk_minds FOREIGN KEY (mind_id)
        REFERENCES core.minds(id) ON DELETE RESTRICT);
"""


def _password() -> str:
    env = Path("/home/daniel/Storage/Dev/hive_mind/.env")
    for line in env.read_text().splitlines():
        if line.startswith("HIVE_PG_PASSWORD="):
            return line.split("=", 1)[1].strip()
    raise AssertionError("HIVE_PG_PASSWORD is not in hive_mind/.env")


def _psql(database: str, sql: str, *, stdin: str | None = None) -> str:
    cmd = ["docker", "exec"]
    if stdin is not None:
        cmd.append("-i")
    cmd += [CONTAINER, "psql", "-U", DB_USER, "-d", database, "-At",
            "-v", "ON_ERROR_STOP=1"]
    if stdin is None:
        cmd += ["-c", sql]
    done = subprocess.run(cmd, input=stdin, capture_output=True, text=True,
                          timeout=180)
    if done.returncode != 0:
        raise AssertionError(f"psql failed: {done.stderr.strip()}")
    return done.stdout.strip()


def _store(path: Path, *statements: str) -> None:
    con = sqlite3.connect(path)
    for stmt in statements:
        con.execute(stmt)
    con.commit()
    con.close()


@pytest.fixture
def staged(tmp_path, monkeypatch):
    """Three stores, a scratch database, and a DSN that reaches it.

    `comms` and `lucent` are the pair being switched. `console` stands for a
    service already on Postgres: its SQLite file is frozen with one card and
    the database has three, which is the shape that made the unrestricted
    load destructive.
    """
    if not os.environ.get("HIVE_PG_TESTS", "1") == "1":  # pragma: no cover
        pytest.skip("HIVE_PG_TESTS=0")
    probe = subprocess.run(
        ["docker", "exec", CONTAINER, "pg_isready", "-U", DB_USER],
        capture_output=True, text=True)
    if probe.returncode != 0:
        pytest.skip(f"{CONTAINER} is not accepting connections")

    _store(
        tmp_path / "comms.db",
        "CREATE TABLE minds (id TEXT PRIMARY KEY, name TEXT)",
        "CREATE TABLE sessions (id TEXT PRIMARY KEY, mind_id TEXT)",
        "INSERT INTO minds VALUES ('m1', 'skippy')",
        "INSERT INTO sessions VALUES ('s1', 'm1')",
    )
    _store(
        tmp_path / "lucent.db",
        "CREATE TABLE notes (id INTEGER PRIMARY KEY, body TEXT)",
        "INSERT INTO notes VALUES (1, 'a memory')",
    )
    _store(
        tmp_path / "console.db",
        "CREATE TABLE cards (id TEXT PRIMARY KEY, mind_id TEXT)",
        "INSERT INTO cards VALUES ('c1', 'm1')",
    )
    monkeypatch.setattr(schema_map, "SOURCES", {
        "comms": "comms.db", "lucent": "lucent.db", "console": "console.db"})
    monkeypatch.setattr(schema_map, "PLACEMENT", {
        ("comms", "minds"): ("core", "minds"),
        ("comms", "sessions"): ("core", "sessions"),
        ("lucent", "notes"): ("memory", "notes"),
        ("console", "cards"): ("board", "cards"),
    })
    monkeypatch.setattr(schema_map, "COLUMN_RENAMES", {})
    monkeypatch.setattr(schema_map, "DROPPED_COLUMNS", {})
    monkeypatch.setattr(load_data, "SKIPPED_SOURCES", {})

    name = f"restricted_test_{uuid.uuid4().hex[:10]}"
    _psql("postgres", f'CREATE DATABASE "{name}";')
    _psql(name, "", stdin=DDL)
    # The console half is already live and has moved on past its file.
    _psql(name, "INSERT INTO core.minds VALUES ('m1', 'skippy');")
    _psql(name, "INSERT INTO board.cards VALUES ('c1','m1'),"
                "('c2','m1'),('c3',NULL);")
    dsn = (f"postgresql://{DB_USER}:{_password()}@127.0.0.1:{HOST_PORT}/"
           f"{name}")
    try:
        yield tmp_path, dsn, name
    finally:
        _psql("postgres", f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE);')


def _rows(database: str, sql: str) -> list[str]:
    out = _psql(database, sql)
    return out.splitlines() if out else []


# ---------------------------------------------------------------------------
# What a restricted load must not touch
# ---------------------------------------------------------------------------

def test_a_restricted_load_leaves_a_store_it_was_not_named_for_alone(staged):
    """The three board cards survive a load of comms and lucent.

    This is the finding. Unrestricted, the load truncates `board.cards` and
    refills it from the frozen file, leaving one card where there were three
    — and reports success.
    """
    base, dsn, name = staged
    report = asyncio.run(load_data.run(
        str(base), dsn, work=base / "snap", keep=True,
        only={"comms", "lucent"}))

    assert [t.ok for t in report.tables] and all(t.ok for t in report.tables)
    assert _rows(name, "SELECT id FROM board.cards ORDER BY id") == [
        "c1", "c2", "c3"]
    assert _rows(name, "SELECT id FROM core.minds") == ["m1"]
    assert _rows(name, "SELECT id FROM core.sessions") == ["s1"]


def test_a_key_reaching_in_from_outside_the_restriction_is_put_back(staged):
    """`board.cards` still refuses a mind that has conversations afterwards.

    Emptying `core.minds` is impossible while a table outside the restriction
    references it, so the key has to be suspended for the load. A suspension
    that is not restored leaves the hive without the constraint and nothing
    says so.
    """
    base, dsn, name = staged
    asyncio.run(load_data.run(str(base), dsn, work=base / "snap", keep=True,
                              only={"comms", "lucent"}))

    assert _rows(name, "SELECT conname FROM pg_constraint "
                       "WHERE conname = 'cards_mind_id_fk_minds'") == [
        "cards_mind_id_fk_minds"]
    assert _rows(name, "SELECT confdeltype FROM pg_constraint "
                       "WHERE conname = 'cards_mind_id_fk_minds'") == ["r"]


def test_a_reload_that_orphans_an_outside_row_refuses_and_changes_nothing(
        staged):
    """The mind a card points at is gone from the store, so nothing loads.

    Restoring the key revalidates it, which is the only thing that can catch
    a restricted load that leaves a table outside the restriction pointing at
    a row that no longer exists.
    """
    base, dsn, name = staged
    _store(base / "comms.db",
           "DELETE FROM sessions WHERE mind_id = 'm1'",
           "DELETE FROM minds WHERE id = 'm1'")

    with pytest.raises(load_data.LoadRefused) as refusal:
        asyncio.run(load_data.run(str(base), dsn, work=base / "snap",
                                  keep=True, only={"comms", "lucent"}))

    assert "cards_mind_id_fk_minds" in str(refusal.value)
    assert _rows(name, "SELECT id FROM core.minds") == ["m1"]
    assert _rows(name, "SELECT id FROM board.cards ORDER BY id") == [
        "c1", "c2", "c3"]


def test_a_restricted_load_counts_what_it_did_not_load_and_says_so(staged):
    """The report states the outside tables were counted, before and after.

    The operator's question after a staged load is "did it touch anything
    else", and the only honest answer is one the run measured. The counts
    are taken inside the load's own transaction, so a run that did move a
    table it was not named for rolls back instead of reporting it — that
    refusal is not reachable through this path today and is deliberately
    not asserted here rather than asserted against a faked loader.
    """
    base, dsn, name = staged
    report = asyncio.run(load_data.run(
        str(base), dsn, work=base / "snap", keep=True,
        only={"comms", "lucent"}))

    counted = [n for n in report.notes
               if "outside this run were counted" in n]
    assert counted, report.notes
    assert counted[0].startswith("1 table(s)")
    left = [n for n in report.notes if n.startswith("restricted to")]
    assert left and "console" in left[0]


# ---------------------------------------------------------------------------
# Drift has to see a changed row, not only a changed count
# ---------------------------------------------------------------------------

def test_a_row_changed_while_the_count_held_is_reported_as_drift(tmp_path,
                                                                monkeypatch):
    """An UPDATE in a stopped store is what the final load must refuse on.

    Counting rows cannot see it: a session status, a surface claim, a
    settings row or a prune's delete-and-insert all leave the count where it
    was, and the cutover's last gate reads "no drift".
    """
    monkeypatch.setattr(schema_map, "SOURCES", {"comms": "comms.db"})
    monkeypatch.setattr(schema_map, "PLACEMENT", {
        ("comms", "minds"): ("core", "minds")})
    live = tmp_path / "comms.db"
    copy = tmp_path / "snap"
    copy.mkdir()
    _store(live,
           "CREATE TABLE minds (id TEXT PRIMARY KEY, name TEXT)",
           "INSERT INTO minds VALUES ('m1', 'skippy')")
    _store(copy / "comms.db",
           "CREATE TABLE minds (id TEXT PRIMARY KEY, name TEXT)",
           "INSERT INTO minds VALUES ('m1', 'skippy')")
    report = load_data.Report()
    load_data._drift(str(tmp_path), {"comms": copy / "comms.db"}, report)
    assert report.drift == []

    _store(live, "UPDATE minds SET name = 'someone else' WHERE id = 'm1'")
    moved = load_data.Report()
    load_data._drift(str(tmp_path), {"comms": copy / "comms.db"}, moved)
    assert moved.drift and "comms.minds" in moved.drift[0]


# ---------------------------------------------------------------------------
# The command the cutover story names has to carry the restriction
# ---------------------------------------------------------------------------

def test_the_cutover_command_carries_the_restriction_it_is_given(capsys):
    """`--only` reaches the loader, proved by the loader's own refusal.

    An unknown source name is refused by `_only` before anything connects,
    so a restriction that never arrives cannot produce this message.
    """
    code = cutover.main(["--base", "/nonexistent", "--dsn",
                         "postgresql://nobody@127.0.0.1:1/none",
                         "--only", "not-a-source"])
    assert code == 2
    assert "not-a-source" in capsys.readouterr().err


# ---------------------------------------------------------------------------
# The pre-switch check has to say "not asked", not "failed"
# ---------------------------------------------------------------------------

def test_an_area_whose_store_was_not_loaded_does_not_fail_the_check():
    """A restricted load leaves areas unasked, and unasked is not failed.

    The first real restricted run reported `FAIL board`, `FAIL tools` and
    `FAIL proxy` with "unable to open database file" — three services it had
    deliberately left alone, named as failures, in the report the operator
    reads to decide whether to switch.
    """
    report = preflight.Preflight()
    report.record("minds", True, "12 mind(s), identical")
    report.record("board", False, "not checked: this run did not load "
                                  "console", checked=False)
    assert report.ok
    assert [a.area for a in report.areas if not a.checked] == ["board"]


def test_a_real_failure_still_fails_the_check():
    """The exclusion is for unasked areas only, not for failures.

    Without this the same change that stops an unasked area failing could
    have made every area pass.
    """
    report = preflight.Preflight()
    report.record("minds", False, "store 11, database 3")
    assert not report.ok
