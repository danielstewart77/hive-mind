--
-- Step 16: roles, the agents holding them, and skills submitted by people
-- (feature 10.18, Role Management).
--
-- A role is a named set of four grants: skills, hooks, a model and the
-- harness's built-in tools. An agent holds roles and may use exactly the
-- union of what they grant; nothing nests, so a role holds grants and never
-- another role.
--
-- `slug` is fixed when the role is made and is what its repo copy is filed
-- under, so renaming a role keeps its link to that copy rather than turning
-- it into a local role beside an orphaned file. Names are unique ignoring
-- case and surrounding space: two roles cannot share a name.
--
-- Role management is switched on per mind, in `managed_minds`, and is a
-- fact of its own rather than "holds at least one row": deleting the last
-- role a mind held must not hand that mind back everything. Every managed
-- mind holds the general role implicitly; `mind_roles` holds the rest.
--
-- `kept_against` is the repo copy a person chose to keep their own version
-- over, by its fingerprint: the role stays marked as differing, and the
-- choice is offered again once the repo copy is no longer that one.
--
-- Neither `managed_minds.mind_id` nor `mind_roles.mind_id` is a key into
-- `core.minds`. A mind created from a
-- role holds it before it has ever started, and a mind registers itself only
-- when it first runs.
--
-- A submission is a skill a person handed the hive as a pull request. The
-- hive never holds the skill itself: the row is the pull request's record,
-- and `merged_at` is what the console last learned about it from GitHub.
--

SELECT pg_catalog.set_config('search_path', '', false);

CREATE TABLE board.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    slug text NOT NULL,
    name text NOT NULL,
    skills text[] NOT NULL DEFAULT '{}',
    hooks text[] NOT NULL DEFAULT '{}',
    model text,
    tools text[] NOT NULL DEFAULT '{}',
    kept_against text,
    created_at double precision NOT NULL,
    updated_at double precision NOT NULL,
    CONSTRAINT roles_pkey PRIMARY KEY (id),
    CONSTRAINT roles_slug_key UNIQUE (slug),
    CONSTRAINT roles_slug_shape CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT roles_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT roles_model_not_blank CHECK (model IS NULL OR btrim(model) <> ''),
    CONSTRAINT roles_tools_known CHECK (
        tools <@ ARRAY['shell', 'files', 'sub-minds', 'web']::text[])
);

CREATE UNIQUE INDEX roles_name_key ON board.roles USING btree (lower(btrim(name)));

CREATE TABLE board.managed_minds (
    mind_id text NOT NULL,
    managed_at double precision NOT NULL,
    CONSTRAINT managed_minds_pkey PRIMARY KEY (mind_id),
    CONSTRAINT managed_minds_mind_not_blank CHECK (btrim(mind_id) <> '')
);

CREATE TABLE board.mind_roles (
    mind_id text NOT NULL,
    role_id bigint NOT NULL,
    assigned_at double precision NOT NULL,
    CONSTRAINT mind_roles_pkey PRIMARY KEY (mind_id, role_id),
    CONSTRAINT mind_roles_role_fkey FOREIGN KEY (role_id)
        REFERENCES board.roles (id) ON DELETE CASCADE,
    CONSTRAINT mind_roles_mind_fkey FOREIGN KEY (mind_id)
        REFERENCES board.managed_minds (mind_id) ON DELETE CASCADE
);

CREATE INDEX mind_roles_role ON board.mind_roles USING btree (role_id);

CREATE TABLE board.skill_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    skill text NOT NULL,
    submitted_by text NOT NULL,
    by_owner boolean NOT NULL,
    new_skill boolean NOT NULL,
    repository text NOT NULL,
    branch text NOT NULL,
    pr_number integer,
    pr_url text,
    merged_at double precision,
    closed_at double precision,
    checked_at double precision,
    created_at double precision NOT NULL,
    CONSTRAINT skill_submissions_pkey PRIMARY KEY (id),
    CONSTRAINT skill_submissions_branch_key UNIQUE (repository, branch),
    CONSTRAINT skill_submissions_skill_not_blank CHECK (btrim(skill) <> ''),
    CONSTRAINT skill_submissions_user_lower CHECK (
        submitted_by = lower(btrim(submitted_by)) AND submitted_by <> '')
);

CREATE INDEX skill_submissions_skill ON board.skill_submissions USING btree (skill);
