--
-- Step 17: the gateway wakes a mind when the session it briefed stops
-- (feature 2.1).
--
-- A watch is a standing request, owned by the conversation that sent a brief,
-- to be woken at every stop of the briefed session. Both ends are keyed on
-- `core.sessions.id`, which survives a rotation, and not on the conversation
-- id a rotation replaces. Either end being ended removes the watch and
-- everything owed under it, which is the requirement that a wake to an ended
-- conversation is dropped and a finished or ended watch wakes nobody.
--
-- `armed` is false from the moment a brief is accepted until that brief's own
-- turn is written, so a turn already running on the briefed session when the
-- ask arrives cannot wake a watch whose brief has not started.
-- `since_turn_id` is the newest turn the briefed session had when the watch
-- armed: the slow check only looks at turns after it.
--
-- `session_stops` is one row for each turn end the gateway has recorded, the
-- latest few for each session. It says whether the last turn finished or died
-- (what the sender fetches); `wake` marks a turn that was itself a wake,
-- which wakes nobody. `turn_id` is the turn the stop is about (the user's row
-- for a chat turn, the assistant's for a terminal one) and a watch is only
-- woken by a stop whose turn_id is not before the watch's `since_turn_id`.
-- `answer_turn_id` is the assistant row holding the answer, when there is one.
--
-- `session_wakes` is one row for each stop a watch is owed a wake for. The
-- unique key (watch, stop) is what makes a stop wake a sender once however
-- many paths find it. A wake moves pending -> claimed -> delivered; it is
-- marked delivered in the same transaction that writes the wake turn's user
-- row, so a crash leaves it pending (retried) or delivered (never again).
--

SELECT pg_catalog.set_config('search_path', '', false);
--
-- Written to run whether or not `core.sql` already made the tables, like step 11.
--

CREATE TABLE IF NOT EXISTS core.session_watches (
    watched_session_id text NOT NULL REFERENCES core.sessions(id) ON DELETE CASCADE,
    sender_session_id text NOT NULL REFERENCES core.sessions(id) ON DELETE CASCADE,
    task text NOT NULL,
    armed boolean NOT NULL DEFAULT false,
    since_turn_id bigint NOT NULL DEFAULT 0,
    -- sha256 of the capability issued to the owning conversation when the
    -- watch was first asked for. Marking the watch finished needs it, which
    -- is what tells two conversations of one mind apart: they share a
    -- credential and only the owner was ever given this.
    capability_digest bytea NOT NULL CHECK (octet_length(capability_digest) = 32),
    created_at double precision NOT NULL DEFAULT EXTRACT(epoch FROM now()),
    PRIMARY KEY (watched_session_id, sender_session_id)
);

CREATE INDEX IF NOT EXISTS session_watches_sender ON core.session_watches (sender_session_id);

CREATE TABLE IF NOT EXISTS core.session_stops (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id text NOT NULL REFERENCES core.sessions(id) ON DELETE CASCADE,
    stop_key text NOT NULL,
    outcome text NOT NULL CHECK (outcome IN ('ended', 'died')),
    wake boolean NOT NULL DEFAULT false,
    turn_id bigint,
    answer_turn_id bigint,
    stopped_at double precision NOT NULL,
    UNIQUE (session_id, stop_key)
);

CREATE TABLE IF NOT EXISTS core.session_wakes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    watched_session_id text NOT NULL,
    sender_session_id text NOT NULL,
    stop_key text NOT NULL,
    outcome text NOT NULL CHECK (outcome IN ('ended', 'died')),
    state text NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending', 'claimed', 'delivered')),
    turn_open boolean NOT NULL DEFAULT false,
    created_at double precision NOT NULL DEFAULT EXTRACT(epoch FROM now()),
    claimed_at double precision,
    delivered_at double precision,
    UNIQUE (watched_session_id, sender_session_id, stop_key),
    FOREIGN KEY (watched_session_id, sender_session_id)
        REFERENCES core.session_watches(watched_session_id, sender_session_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS session_wakes_sender_state ON core.session_wakes (sender_session_id, state);

-- The Chief of Staff page shows a task as stopped when `staff.tasks.stopped_at`
-- is set, which only the old watch ever wrote. With the watch gone the
-- gateway's own records write it: a recorded stop of any session a task is
-- paired with sets it (the first stop wins, as `note_stopped` did), and a user
-- turn written into such a session clears it (`note_running`). Done in the
-- database so the gateway stays ignorant of the ledger and every writer of a
-- turn gets it. `woken_at` is no longer written by anything.
--
-- Moving a ledger task to done is the act that tells the gateway the chief of
-- staff is finished with its sessions (feature 2.1, story 7): one step, so a
-- row can never be done while its session still wakes him. Done in the
-- database because every writer of a status - the ledger tool, the console, a
-- hand edit - must get it for nothing. The watch and the wakes owed under it go
-- together (their foreign key cascades). Defined only where the ledger exists:
-- a deployment that runs comms and not the staff schema has no tasks to move.
DO $do$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_namespace WHERE nspname = 'staff')
       AND pg_catalog.to_regclass('staff.tasks') IS NOT NULL
       AND pg_catalog.to_regclass('staff.task_sessions') IS NOT NULL THEN
        CREATE OR REPLACE FUNCTION staff.end_watches_on_done() RETURNS trigger
        LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
        BEGIN
            DELETE FROM core.session_watches
            WHERE watched_session_id IN (
                SELECT session_id FROM staff.task_sessions
                WHERE task_id = NEW.id);
            RETURN NEW;
        END $fn$;
        CREATE OR REPLACE FUNCTION staff.note_stop_from_gateway() RETURNS trigger
        LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
        BEGIN
            UPDATE staff.tasks t
            SET stopped_at = NEW.stopped_at, updated_at = NEW.stopped_at
            WHERE t.stopped_at IS NULL AND t.status <> 'done' AND t.id IN (
                SELECT task_id FROM staff.task_sessions
                WHERE session_id = NEW.session_id);
            RETURN NEW;
        EXCEPTION WHEN OTHERS THEN
            -- Bookkeeping for a page. It must never refuse a stop.
            RETURN NEW;
        END $fn$;
        DROP TRIGGER IF EXISTS session_stops_note_stop ON core.session_stops;
        CREATE TRIGGER session_stops_note_stop
            AFTER INSERT ON core.session_stops
            FOR EACH ROW EXECUTE FUNCTION staff.note_stop_from_gateway();

        CREATE OR REPLACE FUNCTION staff.note_running_from_gateway() RETURNS trigger
        LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
        BEGIN
            UPDATE staff.tasks t SET stopped_at = NULL
            WHERE t.stopped_at IS NOT NULL AND t.id IN (
                SELECT task_id FROM staff.task_sessions
                WHERE session_id = NEW.session_id);
            RETURN NEW;
        EXCEPTION WHEN OTHERS THEN
            -- Bookkeeping for a page. It must never refuse a turn write.
            RETURN NEW;
        END $fn$;
        DROP TRIGGER IF EXISTS session_turns_note_running ON core.session_turns;
        CREATE TRIGGER session_turns_note_running
            AFTER INSERT ON core.session_turns
            FOR EACH ROW WHEN (NEW.role <> 'assistant')
            EXECUTE FUNCTION staff.note_running_from_gateway();

        DROP TRIGGER IF EXISTS tasks_end_watches_on_done ON staff.tasks;
        CREATE TRIGGER tasks_end_watches_on_done
            AFTER UPDATE OF status ON staff.tasks
            FOR EACH ROW
            WHEN (NEW.status = 'done' AND OLD.status IS DISTINCT FROM 'done')
            EXECUTE FUNCTION staff.end_watches_on_done();
    END IF;
END $do$;
