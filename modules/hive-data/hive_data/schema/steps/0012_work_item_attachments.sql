--
-- Step 12: the files a work item carries (feature 3.7, story 3.7.2).
--
-- Daniel, 2026-11-15: epics, features, stories and tasks can carry
-- attachments, images first. An attachment is kept, comes back with its item
-- after a reload and after a restart, and a file that cannot be kept is
-- reported as failed rather than appearing to succeed.
--
-- The bytes live here, in the row, rather than as a file on the console's
-- `/data` volume beside the minds' pictures. A mind's picture is one file per
-- mind, replaced in place, and owned by nothing in the database. An
-- attachment belongs to a board row, and the board's cascade is the
-- database's: `board.delete_subtree` is one recursive statement. Keeping the
-- bytes in the same database makes that delete take the attachments in the
-- same statement, with no file left behind for nothing to ever serve, and
-- makes an upload one INSERT that either commits or raises - there is no
-- second store whose write can fail after the first one succeeded.
--
-- Keyed by the item's id and nothing else. The kind of the item is not
-- consulted, so a kind added later (the standalone task, story 3.7.4) can
-- carry attachments with no change here. The id is the one column of a work
-- item nothing settable ever changes: a move, a reorder, a status change and
-- a change of type are all updates to the same row.
--
-- `content_type` is the type the console decided from the file's own first
-- bytes, never the one the browser sent: a caller-supplied `text/html`
-- served back from the console's origin would run as a page.
--
-- Written to run on a database whether or not a later baseline already made
-- the table, as the step before it is.
--

SELECT pg_catalog.set_config('search_path', '', false);

CREATE TABLE IF NOT EXISTS board.work_item_attachments (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    item_id text NOT NULL,
    filename text NOT NULL,
    content_type text NOT NULL,
    size_bytes bigint NOT NULL,
    content bytea NOT NULL,
    created_at double precision NOT NULL,
    CONSTRAINT work_item_attachments_pkey PRIMARY KEY (id),
    CONSTRAINT work_item_attachments_item_id_fk_work_items
        FOREIGN KEY (item_id) REFERENCES board.work_items(id)
        ON DELETE CASCADE,
    CONSTRAINT work_item_attachments_not_empty CHECK (size_bytes > 0),
    CONSTRAINT work_item_attachments_size_is_content
        CHECK (size_bytes = octet_length(content)),
    CONSTRAINT work_item_attachments_filename_not_blank
        CHECK (btrim(filename) <> '')
);

CREATE INDEX IF NOT EXISTS work_item_attachments_item_id
    ON board.work_item_attachments USING btree (item_id, id);

COMMENT ON TABLE board.work_item_attachments IS
    'Files attached to a board work item. Deleted with the item.';
COMMENT ON COLUMN board.work_item_attachments.content_type IS
    'The type decided from the file''s own bytes by the console, never the browser''s.';
