"""Every password and token the installer makes, and where a rerun finds them.

The live generated `.env` is the source of truth. The console's credentials
tab rewrites values in place and an operator may edit the file by hand; a
rerun that regenerated, or that trusted its own earlier copy over the live
file, would hand the services a value the database no longer matches. So a
value is taken from the live `.env` first, then from `state/secrets.env` (the
installer's own copy, kept in case `.env` is lost), and only generated when
neither has one. Both files are written 0600.
"""

from __future__ import annotations

import secrets as _random
from pathlib import Path

from installer.paths import Home, write_private


def parse_env(path: Path) -> dict[str, str]:
    """A compose-style env file as a dict; a missing file is empty."""
    out: dict[str, str] = {}
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return out
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        key, _, value = line.partition("=")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
            value = value[1:-1]
        out[key.strip()] = value
    return out


def format_env(values: dict[str, str], header: str = "") -> str:
    """Single-quoted, so compose reads every value literally — a `$` in a
    password is not an interpolation."""
    lines = [f"# {line}" for line in header.splitlines()] if header else []
    for key in sorted(values):
        value = str(values[key])
        if "'" in value or "\n" in value:
            raise ValueError(f"{key}: a value may not contain a single quote or a newline")
        lines.append(f"{key}='{value}'")
    return "\n".join(lines) + "\n"


def generate() -> str:
    return _random.token_urlsafe(32)


def current(home: Home) -> dict[str, str]:
    """What the hive is using now: the installer's copy under the live file."""
    merged = parse_env(home.secrets)
    merged.update(parse_env(home.env_file))
    return merged


def resolve(home: Home, names) -> dict[str, str]:
    """A value for every name: kept where the hive has one, made where not.

    The installer's own copy is rewritten with the result, so a value made
    now survives a lost `.env`.
    """
    have = current(home)
    out = {name: have.get(name) or generate() for name in names}
    keep = parse_env(home.secrets)
    keep.update(out)
    write_private(home.secrets, format_env(keep, "Generated by the hive installer. Do not share."))
    return out


def remember(home: Home, values: dict[str, str]) -> None:
    """Add values made elsewhere (a proxy client key, a tools token)."""
    keep = parse_env(home.secrets)
    keep.update({k: v for k, v in values.items() if v})
    write_private(home.secrets, format_env(keep, "Generated by the hive installer. Do not share."))
