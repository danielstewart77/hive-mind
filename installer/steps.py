"""The install, step by step. Each step is safe to run again.

Order matters and is the requirement: nothing is written to a database until
it has been checked (reachable, able to take the schema, and — when it already
holds a hive — free of the names this install would take).
"""

from __future__ import annotations

import hashlib
import json
import re
import secrets as _random
import shutil
import time
import uuid
from pathlib import Path

from installer import collisions, compose, hive_api, plan, probe, secrets_store
from installer.adapters import dsh, migrate, proxy as proxy_adapter, site, tools
from installer.paths import REPO_BASE, write_private
from installer.runner import NeedInput, Step
from installer.shell import NETWORK, Shell, StepFailed, http_in_network


class Ctx:
    """What a step sees: the install folder, the answers, the host, a shell
    bounded by the step's deadline, and the run's recorded outputs."""

    def __init__(self, installer, sh: Shell):
        self.installer = installer
        self.sh = sh

    @property
    def home(self):
        return self.installer.home

    @property
    def answers(self) -> dict:
        return self.installer.answers

    @property
    def typed(self) -> dict:
        """The secrets typed on the page this run; never written to disk
        except as the .env values they become."""
        return getattr(self.installer, "typed", {}) or {}

    @property
    def host(self):
        return self.installer.host

    @property
    def compose(self) -> list[str]:
        return compose.compose_cmd(self.home)

    def env(self) -> dict[str, str]:
        return secrets_store.parse_env(self.home.env_file)

    def secret(self, answer_key: str) -> str:
        """A secret answer: typed this run, else the live .env's value."""
        typed = str(self.typed.get(answer_key) or "").strip()
        return typed or self.env().get(compose.SECRET_ANSWERS[answer_key], "")

    def set_env(self, **values: str) -> None:
        """Change values in the live .env, keeping everything else in it."""
        current = self.env()
        current.update(values)
        write_private(self.home.env_file, secrets_store.format_env(current, ENV_HEADER))
        secrets_store.remember(self.home, values)

    def output(self, key: str, value=None):
        if value is None:
            return (self.installer.runner.state.get("outputs") or {}).get(key)
        self.installer.runner.record_output(key, value)
        return value

    def web_env(self) -> dict[str, str]:
        """The web proxy settings the services run with."""
        names = [*plan.SERVICE_NAMES, self.answers.get("mind_name") or "mind",
                 *compose.given_hosts(self.answers)]
        return self.host.proxy_env(names)

    def http(self, method: str, url: str, **kw) -> dict:
        """A request from inside the hive network, under the services' proxy."""
        return http_in_network(self.sh, method, url, proxy_env=self.web_env(), **kw)

    def comms(self) -> hive_api.Api:
        return hive_api.Api("comms", f"http://127.0.0.1:{compose.COMMS_HOST_PORT}",
                            self.env()["COMMS_ADMIN_BEARER_TOKEN"])

    def lucent(self) -> hive_api.Api:
        return hive_api.Api("lucent", f"http://127.0.0.1:{compose.LUCENT_HOST_PORT}",
                            self.env()["LUCENT_ADMIN_BEARER_TOKEN"])


ENV_HEADER = ("Generated by the hive installer; the hive's live settings.\n"
              "Readable only by you. A rerun keeps every value here.")


def _minted(ctx: Ctx) -> dict:
    try:
        return json.loads(ctx.home.minted.read_text())
    except (FileNotFoundError, ValueError):
        return {"comms": [], "lucent": []}


def _record_minted(ctx: Ctx, store: str, holders) -> None:
    data = _minted(ctx)
    data[store] = sorted(set(data.get(store, [])) | set(holders))
    write_private(ctx.home.minted, json.dumps(data, indent=2))


def _wait(ctx: Ctx, what: str, probe_fn, timeout: float, pause: float = 3) -> None:
    end = time.monotonic() + timeout
    last = ""
    while time.monotonic() < end:
        try:
            ok, last = probe_fn()
        except StepFailed as exc:
            ok, last = False, str(exc)
        if ok:
            return
        time.sleep(pause)
    raise StepFailed(f"{what} did not come up within {int(timeout)}s: {last}")


def _healthy_in_network(ctx: Ctx, url: str) -> tuple[bool, str]:
    out = ctx.http("GET", url, timeout=8)
    return out.get("status") == 200, str(out.get("error") or out.get("status"))


def _facts(ctx: Ctx) -> dict:
    dsn = ctx.env()["HIVE_DATABASE_URL"]
    facts = ctx.sh.in_network(probe.gather_script(), {"dsn": dsn}, timeout=60, redact=(dsn,))
    if facts.get("error"):
        raise StepFailed(f"the database could not be read: {facts['error']}")
    return facts


def _proxy_admin(ctx: Ctx) -> str:
    """Where a proxy fix is made, said in a way the operator can act on."""
    env = ctx.env()
    return (f"the proxy's admin page, http://{ctx.host.address}:{proxy_adapter.HOST_PORT}/admin "
            f"(user {env.get('HIVE_SEED_USERNAME', '')!r}, password PROXY_ADMIN_PASSWORD in "
            f"{ctx.home.env_file})")


# ---- 1. clone ---------------------------------------------------------------
def _valid_repo(ctx: Ctx, path: Path) -> bool:
    return (path / ".git").is_dir() and ctx.sh.run(
        ["git", "-C", str(path), "rev-parse", "--verify", "HEAD"], check=False).returncode == 0


def clone_repos(ctx: Ctx):
    done = []
    for name in plan.repos(ctx.answers):
        path = ctx.home.repo(name)
        if path.exists() and not _valid_repo(ctx, path):
            # A clone a deadline killed half way: ours, unusable, redone.
            shutil.rmtree(path)
        if path.exists():
            ctx.sh.run(["git", "-C", str(path), "pull", "--ff-only", "--quiet"], timeout=300)
        else:
            # Into a temporary name, renamed only once whole, so an
            # interrupted clone is never mistaken for a repository.
            partial = path.with_name(f".{name}.partial")
            if partial.exists():
                shutil.rmtree(partial)
            ctx.sh.run(["git", "clone", "--quiet", f"{REPO_BASE}/{name}.git", str(partial)],
                       timeout=900)
            if not _valid_repo(ctx, partial):
                raise StepFailed(f"the clone of {name} has no HEAD")
            partial.rename(path)
        head = ctx.sh.run(["git", "-C", str(path), "rev-parse", "--short", "HEAD"]).stdout.strip()
        done.append(f"{name}@{head}")
    return ", ".join(done)


# ---- 2. dsh tree ------------------------------------------------------------
def _dsh_fresh(ctx: Ctx) -> Path:
    return ctx.home.root / "dsh.new"


def build_dsh_tree(ctx: Ctx):
    """Built beside the live tree. A running mind has the live one mounted,
    so the new tree is swapped in by `start_mind`, which recreates the mind
    in the same breath; only a first install swaps it in here."""
    repo = ctx.home.repo("hive-harness-dsh")
    head = ctx.sh.run(["git", "-C", str(repo), "rev-parse", "HEAD"]).stdout.strip()
    fresh = _dsh_fresh(ctx)
    if dsh.tree_built(ctx.home.dsh) and ctx.output("dsh_head") == head:
        return f"tree at {head[:8]} already built"
    if dsh.tree_built(fresh) and ctx.output("dsh_fresh_head") == head:
        return f"tree at {head[:8]} built, waiting to be swapped in"
    if fresh.exists():
        shutil.rmtree(fresh)
    ctx.sh.run(dsh.build_tree(repo, fresh, ctx.host.proxy_env(plan.SERVICE_NAMES)),
               timeout=3600, env={"DOCKER_BUILDKIT": "1"})
    if not dsh.tree_built(fresh):
        raise StepFailed(f"the dsh build produced no launcher at {dsh.LAUNCHER}")
    ctx.output("dsh_fresh_head", head)
    if not dsh.tree_built(ctx.home.dsh):
        _swap_dsh(ctx)
        return f"tree built at {head[:8]}"
    return f"tree built at {head[:8]}; swapped in when the mind restarts"


def _swap_dsh(ctx: Ctx) -> None:
    fresh, old = _dsh_fresh(ctx), ctx.home.root / "dsh.old"
    if old.exists():
        shutil.rmtree(old)
    if ctx.home.dsh.exists():
        ctx.home.dsh.rename(old)
    fresh.rename(ctx.home.dsh)
    shutil.rmtree(old, ignore_errors=True)
    ctx.output("dsh_head", ctx.output("dsh_fresh_head"))


# ---- 3. config --------------------------------------------------------------
def render_config(ctx: Ctx):
    home, answers = ctx.home, ctx.answers
    current = secrets_store.current(home)
    if plan.runs_here(answers, "postgres") and not current.get("HIVE_PG_PASSWORD") and \
            ctx.sh.run(["docker", "volume", "inspect", compose.PG_VOLUME],
                       check=False).returncode == 0:
        # A new password over an old volume is a database that refuses every
        # service, reported as each of them being unhealthy.
        raise StepFailed(
            f"a Docker volume named {compose.PG_VOLUME} already holds a database, and this "
            f"install folder has no password for it. Put the earlier install's .env back in "
            f"{home.root}, or remove the volume (docker volume rm {compose.PG_VOLUME}) if its "
            "data is not wanted, then run again")
    generated = secrets_store.resolve(home, compose.secret_names(answers))
    values = compose.env_values(home, answers, generated, current, typed=ctx.typed)
    rendered = compose.render(home, answers, ctx.host)
    compose.prepare_mounts(rendered)
    write_private(home.env_file, secrets_store.format_env(values, ENV_HEADER))
    secrets_store.remember(home, values)
    # 0600 as well: a web proxy's credential is written into it literally.
    write_private(home.compose_file, rendered.text())
    ctx.sh.run([*ctx.compose, "config", "--quiet"], timeout=60)
    return f"{len(rendered.compose['services'])} services"


# ---- 4. network -------------------------------------------------------------
def create_network(ctx: Ctx):
    if ctx.sh.run(["docker", "network", "inspect", NETWORK], check=False).returncode == 0:
        return "exists"
    ctx.sh.run(["docker", "network", "create", NETWORK])
    return "created"


# ---- 5. images --------------------------------------------------------------
def build_images(ctx: Ctx):
    ctx.sh.run([*ctx.compose, "build"], timeout=5400)
    ctx.sh.run([*ctx.compose, "pull", "--ignore-buildable", "--quiet"], timeout=1800)
    doc = json.loads(ctx.home.compose_file.read_text())
    if compose.CONSOLE not in doc["services"]:
        # The first admin is seeded with the console's own code, so its image
        # is built even when the console is not installed.
        ctx.sh.run(compose.console_image_build(ctx.home, ctx.host), timeout=3600)
    return "built"


# ---- 6. existing services ---------------------------------------------------
def check_existing(ctx: Ctx):
    a = ctx.answers
    checked = []
    if not plan.runs_here(a, "postgres"):
        dsn = ctx.env()["HIVE_DATABASE_URL"]
        facts = ctx.sh.in_network(probe.gather_script(), {"dsn": dsn}, timeout=60, redact=(dsn,))
        if facts.get("error"):
            raise StepFailed(f"the database at {a['postgres_host']}:{a.get('postgres_port')} "
                             f"cannot be reached from inside the hive: {facts['error']}")
        checked.append("database")
    targets = []
    if not plan.runs_here(a, "proxy"):
        targets.append(("proxy", compose.proxy_url(a) + "/health"))
    if plan.runs_elsewhere(a, "embeddings"):
        targets.append(("embedding service", compose.embeddings_url(a) + "/api/tags"))
    if plan.mode(a, "voice") == plan.EXISTING:
        targets.append(("voice server", compose.voice_url(a) + "/health"))
    for label, url in targets:
        out = ctx.http("GET", url, timeout=10)
        if not out.get("status"):
            raise StepFailed(f"the {label} at {url.rsplit('/', 1)[0]} cannot be reached from "
                             f"inside the hive: {out.get('error')}")
        checked.append(label)
    return ", ".join(checked) or "nothing existing"


# ---- 7. database ------------------------------------------------------------
def start_database(ctx: Ctx):
    if not plan.runs_here(ctx.answers, "postgres"):
        return "existing database"
    ctx.sh.run([*ctx.compose, "up", "-d", compose.POSTGRES], timeout=300)

    def healthy():
        out = ctx.sh.run(["docker", "inspect", "-f", "{{.State.Health.Status}}",
                          compose.POSTGRES], check=False).stdout.strip()
        return out == "healthy", out
    _wait(ctx, "the database", healthy, 240)
    return "healthy"


# ---- 8. schema check --------------------------------------------------------
def schema_check(ctx: Ctx):
    report = migrate.check(ctx.sh, ctx.env()["HIVE_DATABASE_URL"])
    ctx.output("facts", _facts(ctx))
    pending = report.get("pending") or []
    return f"{len(pending)} schema step(s) to apply" if pending else "schema current"


# ---- 9. refusals ------------------------------------------------------------
def refuse_collisions(ctx: Ctx):
    a = ctx.answers
    facts = ctx.output("facts") or {}
    holders = compose.service_holders(a)
    holders = {"comms": [*holders["comms"], a["mind_name"]],
               "lucent": [*holders["lucent"], a["mind_name"]]}
    problems = collisions.refusals(facts, admin=a["admin_username"], mind_name=a["mind_name"],
                                   mind_id=a["mind_id"], holders=holders, ours=_minted(ctx))
    if problems:
        raise StepFailed("this database already holds a hive, and nothing was written: "
                         + "; ".join(problems))
    return "an existing hive, no collisions" if collisions.hive_present(facts) else "a new hive"


# ---- 10. schema apply -------------------------------------------------------
def schema_apply(ctx: Ctx):
    report = migrate.apply(ctx.sh, ctx.env()["HIVE_DATABASE_URL"])
    return f"schema at {report.get('version')}"


# ---- 11. the first admin ----------------------------------------------------
def seed_admin(ctx: Ctx):
    """The admin account, made with the console's own seed code.

    hive_site's `seed_first_user` in the console image (which carries it),
    whatever pieces are ticked: without an account nothing can own the mind
    or sign in. It writes only into an empty account store, so against an
    existing hive it does nothing and the account is the one the collision
    check already found.
    """
    env = ctx.env()
    admin = collisions.username(ctx.answers["admin_username"])
    out = ctx.sh.in_network(site.SEED_SCRIPT, {
        "dsn": env["HIVE_DATABASE_URL"], "username": admin,
        "password": env.get("HIVE_SEED_PASSWORD", "")},
        timeout=120, image=compose.CONSOLE_IMAGE,
        redact=(env["HIVE_DATABASE_URL"], env.get("HIVE_SEED_PASSWORD", "")))
    if out.get("error"):
        raise StepFailed(f"the admin account could not be made: {out['error']}")
    if not out.get("exists"):
        raise StepFailed(f"the admin {admin!r} has no account and none was made: the account "
                         "store already holds other accounts")
    return "admin made" if out.get("created") else "admin exists"


# ---- 12. services -----------------------------------------------------------
def _infra(ctx: Ctx) -> list[str]:
    mind = ctx.answers["mind_name"]
    skip = {mind, compose.TELEGRAM, compose.DISCORD}
    doc = json.loads(ctx.home.compose_file.read_text())
    return [s for s in doc["services"] if s not in skip]


def start_services(ctx: Ctx):
    if plan.runs_here(ctx.answers, "proxy"):
        migrated = bool((ctx.output("facts") or {}).get("proxy_migrated"))
        ctx.set_env(**{proxy_adapter.ALLOW_CREATE: "false" if migrated else "true"})
    services = _infra(ctx)
    ctx.sh.run([*ctx.compose, "up", "-d", *services], timeout=900)
    # /health is a machine route on comms: asked with the admin bearer.
    for name, api in (("comms", ctx.comms()), ("lucent", ctx.lucent())):
        def up(api=api):
            status, _ = api.request("GET", "/health")
            return status == 200, str(status)
        _wait(ctx, name, up, 240)
    return ", ".join(services)


# ---- 13. proxy --------------------------------------------------------------
def _digest(*parts) -> str:
    return hashlib.sha256("\x00".join(str(p) for p in parts).encode()).hexdigest()


def _put_row(ctx: Ctx, key: str, fingerprint: str, add) -> bool:
    """Add a proxy row; when it existed and what this install gave for it has
    changed since it was last confirmed, rewrite it with `--update`.

    The add commands keep an existing row untouched, so without this a key
    or a context window changed on a rerun would be silently dropped. True
    when the row was rewritten."""
    out = add(update=False)
    existed = out.get("created") is False
    if existed and (ctx.output(key) or {}).get("value") != fingerprint:
        add(update=True)
        return True
    return False


def proxy_setup(ctx: Ctx):
    a = ctx.answers
    if not plan.runs_here(a, "proxy"):
        if not ctx.env().get("MIND_PROXY_KEY"):
            raise StepFailed("no client key for the existing proxy")
        return "existing proxy"
    _wait(ctx, "the proxy", lambda: _healthy_in_network(ctx, proxy_adapter.URL + "/health"), 240)
    # Migrated now: the flag goes off, so a later start never builds a
    # schema from nothing.
    ctx.set_env(**{proxy_adapter.ALLOW_CREATE: "false"})
    ctx.sh.run([*ctx.compose, "up", "-d", proxy_adapter.SERVICE], timeout=300)
    _wait(ctx, "the proxy", lambda: _healthy_in_network(ctx, proxy_adapter.URL + "/health"), 240)
    # The hive's own models first: lucent embeds and classifies with them,
    # and the capture hook classifies with the second.
    fingerprints, rewrote = _register_local_models(ctx)
    provider = a["provider_kind"]
    base_url = str(a.get("provider_base_url") or "")
    api_key = ctx.secret("provider_api_key")
    window = int(a.get("provider_model_window") or 200000)
    model = a["provider_model"]
    fingerprints.update({f"provider:{provider}": _digest(provider, base_url, api_key),
                         f"model:{model}": _digest(provider, window)})
    rewrote |= _put_row(ctx, f"provider:{provider}", fingerprints[f"provider:{provider}"],
                       lambda update: proxy_adapter.add_provider(
                           ctx.sh, ctx.compose, name=provider, kind=provider,
                           base_url=base_url, api_key=api_key, update=update))
    rewrote |= _put_row(ctx, f"model:{model}", fingerprints[f"model:{model}"],
                        lambda update: proxy_adapter.add_model(
                            ctx.sh, ctx.compose, provider=provider, model=model,
                            context_window=window, update=update))
    key = proxy_adapter.mint_key(ctx.sh, ctx.compose, client=a["mind_name"])
    if key:
        ctx.set_env(MIND_PROXY_KEY=key)
    elif not ctx.env().get("MIND_PROXY_KEY"):
        raise StepFailed(f"the proxy already has a key for {a['mind_name']!r} that this install "
                         f"did not record; revoke it on {_proxy_admin(ctx)} and run again")
    # Done only once a real completion has come back through the proxy: a
    # wrong upstream key is found here, with the provider's own words, not
    # at the mind's first turn.
    proxy_adapter.check_model(ctx.sh, ctx.compose, model=model)
    for name, value in fingerprints.items():
        ctx.output(name, {"value": value})
    checked = "; a test completion answered" + ("; rows updated" if rewrote else "")
    return (f"{compose.EMBEDDING_MODEL} and {compose.CLASSIFIER_MODEL} on {LOCAL_PROVIDER}; "
            + ("provider, model and the hive's key" if key else
               "provider, model; the hive's key kept") + checked)


#: The proxy's provider for the hive's own Ollama. Named apart from the
#: operator's provider, which may be another Ollama.
LOCAL_PROVIDER = "hive-ollama"
#: The context window an Ollama model is registered with when its tag does
#: not say one.
LOCAL_WINDOW = 32768
_DERIVED_TAG = re.compile(r"^(?P<base>[^:\s]+:[^:\s]+?)-(?P<k>\d+)k$")


def local_window(tag: str) -> int:
    found = _DERIVED_TAG.match(tag)
    return int(found.group("k")) * 1024 if found else LOCAL_WINDOW


def ollama_commands(tag: str) -> list[list[str]]:
    """What makes `tag` present in an Ollama: a pull, or for a tag that is a
    library model with a context size of its own (`gpt-oss:20b-32k`, which
    no registry serves) a pull of the base and a create with that `num_ctx`."""
    found = _DERIVED_TAG.match(tag)
    if not found:
        return [["ollama", "pull", tag]]
    base, ctx_len = found.group("base"), int(found.group("k")) * 1024
    modelfile = f"/tmp/{tag.replace(':', '_').replace('/', '_')}.Modelfile"
    return [["ollama", "pull", base],
            ["sh", "-c", f"printf 'FROM {base}\\nPARAMETER num_ctx {ctx_len}\\n' > {modelfile} "
                         f"&& ollama create {tag} -f {modelfile}"]]


def _register_local_models(ctx: Ctx) -> tuple[dict, bool]:
    """The hive's Ollama as a proxy provider, its embedding model
    (purpose embedding) and its classifier (purpose chat) on it."""
    url = compose.embeddings_url(ctx.answers)
    rows = {f"provider:{LOCAL_PROVIDER}": (_digest("ollama", url), lambda update: (
        proxy_adapter.add_provider(ctx.sh, ctx.compose, name=LOCAL_PROVIDER, kind="ollama",
                                   base_url=url, update=update)))}
    for model, purpose in ((compose.EMBEDDING_MODEL, "embedding"),
                           (compose.CLASSIFIER_MODEL, "chat")):
        window = local_window(model)
        rows[f"model:{model}"] = (_digest(LOCAL_PROVIDER, window, purpose), (
            lambda update, model=model, window=window, purpose=purpose:
            proxy_adapter.add_model(ctx.sh, ctx.compose, provider=LOCAL_PROVIDER, model=model,
                                    context_window=window, purpose=purpose, update=update)))
    rewrote = False
    for key, (fingerprint, add) in rows.items():
        rewrote |= _put_row(ctx, key, fingerprint, add)
    return {key: fingerprint for key, (fingerprint, _) in rows.items()}, rewrote


# ---- 14. embeddings ---------------------------------------------------------
def _mem_gb() -> float:
    try:
        for line in Path("/proc/meminfo").read_text().splitlines():
            if line.startswith("MemTotal:"):
                return int(line.split()[1]) / 1024 / 1024
    except OSError:
        pass
    return 0.0


def embeddings(ctx: Ctx):
    """The models the hive's Ollama serves, pulled before the proxy that
    serves them is set up. Nothing is tested here: every model is checked
    through the proxy, with the key the hive uses."""
    a = ctx.answers
    if not plan.runs_here(a, "embeddings"):
        return "no local models to pull"
    notes = []
    if 0 < _mem_gb() < 10:
        notes.append(f"only {_mem_gb():.0f} GB of memory: embedding will be slow")
    models = []
    if plan.runs_here(a, "proxy"):
        models += [compose.EMBEDDING_MODEL, compose.CLASSIFIER_MODEL]
    if "tools" in plan.installed(a):
        models.append(str(a.get("tools_ollama_model") or "qwen3:4b"))
    for model in models:
        for argv in ollama_commands(model):
            ctx.sh.run([*ctx.compose, "exec", "-T", compose.OLLAMA, *argv], timeout=3600)
    return "; ".join([("pulled " + ", ".join(models)) if models else "nothing to pull", *notes])


# ---- 14b. the hive's models -------------------------------------------------
MODEL_CHOICES = {
    # answer key: (.env name, purpose, the label asked, the default)
    "embedding_model": (compose.EMBEDDING_MODEL_VAR, "embedding",
                        "The embedding model lucent stores memory with", compose.EMBEDDING_MODEL),
    "classifier_model": (compose.CLASSIFIER_MODEL_VAR, "chat",
                         "The model lucent and the mind's memory capture classify with",
                         compose.CLASSIFIER_MODEL),
}


def _chosen(ctx: Ctx, key: str, offered: list[str]) -> str:
    """The model chosen for `key`: answered on the page, else the one this
    hive already uses; asked from the proxy's own listing when neither."""
    env_name, purpose, label, default = MODEL_CHOICES[key]
    where = f"the proxy at {compose.proxy_url(ctx.answers)}"
    chosen = str(ctx.answers.get(key) or ctx.env().get(env_name) or "").strip()
    if not offered:
        raise StepFailed(f"{where} lists no models this hive's key may use; "
                         "add one to the proxy and run again")
    if not chosen:
        raise NeedInput(key, label, sorted(offered, key=lambda m: m != default))
    if chosen not in offered:
        _ask_again(ctx, key, offered,
                   f"{where} does not offer the {purpose} model {chosen!r} chosen for this hive "
                   f"(it offers: {', '.join(offered)})")
    return chosen


def _forget(ctx: Ctx, key: str, env_name: str) -> None:
    """A bad model pick: forgotten from the answers, the live .env and the
    installer's own copy, so nothing brings it back."""
    ctx.answers.pop(key, None)
    ctx.installer.save()
    ctx.set_env(**{env_name: ""})
    secrets_store.forget(ctx.home, [env_name])


def _ask_again(ctx: Ctx, key: str, offered: list[str], reason: str):
    """A bad pick is forgotten and asked for again in this run, with why and
    the proxy's models. A pick whose test call failed stays a choice: the
    failure may have been the proxy's, not the model's, and a hive's working
    embedding model is not swapped for another over one bad answer. Only a
    model proven too wide is left out; when that leaves none, no pick can
    fix it and the step fails."""
    env_name, _, label, default = MODEL_CHOICES[key]
    _forget(ctx, key, env_name)
    too_wide = set(ctx.output("too_wide") or []) if key == "embedding_model" else set()
    choices = [m for m in sorted(offered, key=lambda m: m != default) if m not in too_wide]
    if not choices:
        raise StepFailed(f"{reason}. The proxy offers no other model to choose; add one to "
                         "the proxy and run again")
    raise NeedInput(key, label, choices, reason=reason)


def resolve_models(ctx: Ctx):
    """The embedding and classifier models, each offered by the proxy and
    each answering one real call made with the hive's key, before lucent is
    pointed at them."""
    a, key = ctx.answers, ctx.env().get("MIND_PROXY_KEY", "")
    url, web, own = compose.proxy_url(a), ctx.web_env(), plan.runs_here(a, "proxy")
    chat = proxy_adapter.list_models(ctx.sh, url, key, purpose="chat", proxy_env=web)
    embedders = proxy_adapter.list_models(ctx.sh, url, key, purpose="embedding", proxy_env=web)
    embedder = _chosen(ctx, "embedding_model", embedders)
    classifier = _chosen(ctx, "classifier_model", chat)
    try:
        if own:
            dims = proxy_adapter.check_model(ctx.sh, ctx.compose, model=embedder,
                                             harness=None).get("dimensions")
        else:
            dims = proxy_adapter.embedding_dimensions(ctx.sh, url, key, embedder, proxy_env=web)
        # Narrower vectors are zero-padded by lucent; wider ones do not fit.
        if not dims or dims > compose.EMBEDDING_DIMENSIONS:
            ctx.output("too_wide", sorted({*(ctx.output("too_wide") or []), embedder}))
            raise StepFailed(f"{embedder!r} answered {dims} dimensions; lucent stores at most "
                             f"{compose.EMBEDDING_DIMENSIONS} (memory.memories.embedding is "
                             f"vector({compose.EMBEDDING_DIMENSIONS})). Choose another "
                             "embedding model")
    except StepFailed as exc:
        _ask_again(ctx, "embedding_model", embedders, str(exc))
    try:
        if own:
            proxy_adapter.check_model(ctx.sh, ctx.compose, model=classifier)
        else:
            proxy_adapter.classify_check(ctx.sh, url, key, classifier, proxy_env=web)
    except StepFailed as exc:
        _ask_again(ctx, "classifier_model", chat, str(exc))
    a["embedding_model"], a["classifier_model"] = embedder, classifier
    ctx.set_env(**{compose.EMBEDDING_MODEL_VAR: embedder, compose.CLASSIFIER_MODEL_VAR: classifier})
    # Lucent and the console started before the key and the models were
    # known; `up -d` recreates whichever the .env change reaches.
    ctx.sh.run([*ctx.compose, "up", "-d", compose.LUCENT,
                *([compose.CONSOLE] if "console" in plan.installed(a) else [])], timeout=300)
    return f"embedding {embedder} ({dims} dimensions), classifier {classifier}"


# ---- 15. reachability -------------------------------------------------------
def _endpoints(ctx: Ctx) -> list[tuple[str, str]]:
    a = ctx.answers
    pieces = plan.installed(a)
    out = [("comms", compose.COMMS_URL + "/health"), ("lucent", compose.LUCENT_URL + "/health"),
           ("proxy", compose.proxy_url(a) + "/health")]
    if "embeddings" in pieces:
        out.append(("embedding service", compose.embeddings_url(a) + "/api/tags"))
    if "console" in pieces:
        out.append(("console", f"http://{compose.CONSOLE}:{compose.CONSOLE_PORT}/"))
    if "terminal" in pieces:
        out.append(("terminal", f"http://{compose.TERMINAL}:{compose.TERMINAL_PORT}/"))
    if "tools" in pieces:
        out.append(("tools", tools.URL + "/health"))
    if compose.voice_url(a):
        out.append(("voice", compose.voice_url(a) + "/health"))
    return out


def reachability(ctx: Ctx):
    unreachable = []
    for label, url in _endpoints(ctx):
        last = {}
        for _ in range(20):
            last = ctx.http("GET", url, timeout=8)
            if last.get("status"):
                break
            time.sleep(3)
        if not last.get("status"):
            unreachable.append(f"{label} ({url}): {last.get('error')}")
    if unreachable:
        raise StepFailed("not reachable from inside the hive: " + "; ".join(unreachable))
    return "every service answers"


# ---- 16. service credentials ------------------------------------------------
def _tools_token_ok(ctx: Ctx, token: str) -> bool:
    out = ctx.http("GET", tools.URL + tools.TOKEN_CHECK,
                   headers={"Authorization": f"Bearer {token}"}, timeout=10)
    return out.get("status") not in (0, 401, 403)


def mint_credentials(ctx: Ctx):
    a, env = ctx.answers, ctx.env()
    holders = compose.service_holders(a)
    admin = collisions.username(a["admin_username"])
    done = {}
    for store, api in (("comms", ctx.comms()), ("lucent", ctx.lucent())):
        wanted = {h: env[compose.token_var(store.upper(), h)] for h in holders[store]}
        done[store] = hive_api.mint(api, wanted, admin, role=hive_api.SERVICE,
                                    on_minted=lambda h, s=store: _record_minted(ctx, s, [h]))
    if "tools" in plan.installed(a):
        token = env.get("HIVE_TOOLS_TOKEN")
        # Checked, not trusted: a tools database rebuilt since has none of
        # the tokens this install recorded.
        if not token or not _tools_token_ok(ctx, token):
            token = tools.mint_token(ctx.sh, ctx.compose)
            ctx.set_env(HIVE_TOOLS_TOKEN=token)
            if "console" in plan.installed(a):
                ctx.sh.run([*ctx.compose, "up", "-d", compose.CONSOLE], timeout=300)
            done["tools"] = "token minted"
        else:
            done["tools"] = "token kept"
    return done


# ---- 17. model --------------------------------------------------------------
def _runtime(ctx: Ctx) -> Path:
    return ctx.home.mind(ctx.answers["mind_name"]) / "runtime.yaml"


def _file_model(path: Path) -> str:
    try:
        found = re.search(r"^default_model:\s*(\S+)\s*$", path.read_text(), re.M)
    except OSError:
        return ""
    return found.group(1).strip("'\"") if found else ""


def choose_model(ctx: Ctx):
    models = proxy_adapter.list_models(ctx.sh, compose.proxy_url(ctx.answers),
                                       ctx.env()["MIND_PROXY_KEY"], harness="dsh",
                                       proxy_env=ctx.web_env())
    if not models:
        raise StepFailed("the proxy offers no model for dsh; add one on "
                         f"{_proxy_admin(ctx)} and run again")
    ctx.output("models", models)
    # The mind's own file is the truth once it exists: a model changed on
    # the console since is the one kept.
    current = _file_model(_runtime(ctx))
    if current in models:
        ctx.answers["model"] = current
        return current
    chosen = ctx.answers.get("model")
    if chosen in models:
        return chosen
    raise NeedInput("model", "The model the mind runs on", models)


